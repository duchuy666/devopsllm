#!/usr/bin/env python3
"""Generate the Sock Shop incident dashboard (Grafana) from the same PromQL the collector uses.

Writes infra/observability/grafana-dashboards-values.yaml, a Helm values overlay. Deploy with
scripts/deploy_grafana_dashboard.sh only while the collection controller is stopped.
"""
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from app.metric_queries import QUERIES

OUT=ROOT/'infra/observability/grafana-dashboards-values.yaml'


def panel(pid,title,expr,legend,unit,x,y,w=12,h=8,kind='timeseries',datasource='prometheus'):
    return {'id':pid,'title':title,'type':kind,'gridPos':{'x':x,'y':y,'w':w,'h':h},
            'datasource':{'type':datasource,'uid':datasource},
            'fieldConfig':{'defaults':{'unit':unit},'overrides':[]},
            'targets':[{'refId':'A','expr':expr,'legendFormat':legend,'datasource':{'type':datasource,'uid':datasource}}]}


def dashboard():
    panels=[
        panel(1,'Alert đang firing','sum by (alertname,pod,service,route) (ALERTS{alertstate="firing"})',
              '{{alertname}} {{pod}}{{service}} {{route}}','none',0,0,24,5,'table'),
        panel(2,'CPU theo Pod (core)',QUERIES['cpu'],'{{pod}}','none',0,5),
        panel(3,'CPU limit theo Pod (core)',QUERIES['cpu_limit'],'{{pod}}','none',12,5),
        panel(4,'Memory working set theo Pod',QUERIES['memory'],'{{pod}}','bytes',0,13),
        panel(5,'Memory limit theo Pod',QUERIES['memory_limit'],'{{pod}}','bytes',12,13),
        panel(6,'Request rate theo route (req/s)',QUERIES['request_rate'],'{{service}} {{route}}','reqps',0,21),
        panel(7,'Latency trung bình theo route',QUERIES['latency_mean'],'{{service}} {{route}}','s',12,21),
        panel(8,'Tỷ lệ lỗi 5xx theo route',QUERIES['error_rate'],'{{service}} {{route}}','percentunit',0,29),
        panel(9,'Pod Ready',QUERIES['ready'],'{{pod}}','none',12,29),
        panel(10,'Container restarts',QUERIES['restarts'],'{{pod}} {{container}}','none',0,37),
        {'id':11,'title':'Log Sock Shop (Loki)','type':'logs','gridPos':{'x':12,'y':37,'w':12,'h':8},
         'datasource':{'type':'loki','uid':'loki'},
         'targets':[{'refId':'A','expr':'{namespace="sock-shop"}','datasource':{'type':'loki','uid':'loki'}}]},
        {'id':12,'title':'Trace (Jaeger)','type':'text','gridPos':{'x':0,'y':45,'w':24,'h':3},
         'options':{'mode':'markdown','content':'Mở **Explore → Jaeger** để xem trace theo service; datasource uid `jaeger`.'}},
    ]
    return {'uid':'sockshop-incident','title':'Sock Shop – Incident overview','tags':['sock-shop','incident'],
            'timezone':'browser','schemaVersion':39,'refresh':'15s','time':{'from':'now-30m','to':'now'},'panels':panels}


def main():
    values={'dashboardProviders':{'dashboardproviders.yaml':{'apiVersion':1,'providers':[
                {'name':'shyn','orgId':1,'folder':'SHYN','type':'file','disableDeletion':True,'editable':False,
                 'options':{'path':'/var/lib/grafana/dashboards/shyn'}}]}},
            'dashboards':{'shyn':{'sockshop-incident':{'json':json.dumps(dashboard(),ensure_ascii=False,indent=1)}}}}
    # JSON is a subset of YAML; avoids a YAML dependency and keeps the overlay byte-stable.
    OUT.write_text('# Generated by scripts/build_grafana_dashboard.py; do not edit by hand.\n'+json.dumps(values,ensure_ascii=False,indent=1)+'\n')
    print(str(OUT))


if __name__=='__main__':main()
